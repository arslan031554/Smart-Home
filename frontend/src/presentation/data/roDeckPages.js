export function localizeDeckPageRo(page) {
  const data = roPageData[page.slug];
  if (!data) {
    return { ...page, language: 'ro' };
  }

  const title = data.title || page.title;
  const menuLabel = data.menuLabel || data.title || page.menuLabel;
  const defaultEyebrow = `${page.section === 'technology' ? 'TEHNOLOGIE' : page.section === 'buildings' ? 'CLĂDIRI ȘI DESTINAȚII' : 'SOLUȚII'} · ${title.toLocaleUpperCase('ro-RO')}`;

  return {
    ...page,
    language: 'ro',
    title,
    menuLabel,
    eyebrow: data.eyebrow || defaultEyebrow,
    supportingHeadline: data.supportingHeadline || page.supportingHeadline,
    heroDescription: data.heroDescription || page.heroDescription,
    primaryCta: data.primaryCta || 'Află cât costă →',
    secondaryCta: data.secondaryCta || (page.section === 'technology' ? 'Descoperă tehnologia' : page.section === 'buildings' ? 'Vezi tehnologiile' : 'Vezi portofoliul'),
    sectionHeading: data.sectionHeading || page.sectionHeading,
    resultLine: data.resultLine || page.resultLine,
    features: (data.features || []).map((feature, index) => ({
      icon: feature.icon || page.features?.[index]?.icon || '✨',
      title: feature.title,
      description: feature.description,
    })),
    longForm: data.longForm || page.longForm,
    closingDescription: data.closingDescription || page.closingDescription,
    closingCta: data.closingCta || 'Configurează un proiect →',
    seoTitle: data.seoTitle || `${title} | Green Electric`,
    seoDescription: data.seoDescription || page.seoDescription,
    imageDirection: data.imageDirection || `${title} într-o clădire modernă`,
  };
}

